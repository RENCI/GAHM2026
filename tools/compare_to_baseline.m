%
% Usage:
%   cd into the GAHM26 directory, then run:
%     >> compare_to_baseline
%
% Tolerances:
%   velocity_tol  - m/s, absolute tolerance for VelU, VelV  (default 1e-10)
%   pressure_tol  - mb,  absolute tolerance for Press        (default 1e-10)
%   distance_tol  - m,   absolute tolerance for Rmax, RmaxQ  (default 1e-6)
%   parameter_tol -      absolute tolerance for B, Bg, phi    (default 1e-10)
%
% Requires:
%   tools/baseline_env1.mat and/or tools/baseline_env3.mat
%   (generated by generate_baseline.m)
%
%                    February 2026
%--------------------------------------------------------------------------

