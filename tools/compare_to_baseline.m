%% ========================================================================
%  Helper functions
%  ========================================================================

function [npass, nfail] = compare_all_fields(bl, Reggrid_out, Reggrid_TC_out, ...
                              Reggrid_Env_out, GAHM_out, Trackdata, ...
                              vel_tol, press_tol, dist_tol, param_tol)

    npass = 0;
    nfail = 0;

    % Check timestep counts
    nt = length(Reggrid_out);
    if nt ~= bl.nt
        fprintf('  FAIL: timestep count mismatch (baseline=%d, current=%d)\n', bl.nt, nt);
        nfail = nfail + 1;
        return
    end
    fprintf('  Timesteps: %d (match)\n', nt);

    % --- TC output fields ---
    fprintf('  Gridded TC output:\n');
    [p, f] = compare_cell_field(bl.TC_VelU, Reggrid_TC_out, 'VelU', 'TC_VelU', vel_tol);
    npass = npass + p; nfail = nfail + f;

    [p, f] = compare_cell_field(bl.TC_VelV, Reggrid_TC_out, 'VelV', 'TC_VelV', vel_tol);
    npass = npass + p; nfail = nfail + f;

    [p, f] = compare_cell_field(bl.TC_Press, Reggrid_TC_out, 'Press', 'TC_Press', press_tol);
    npass = npass + p; nfail = nfail + f;

    % --- Env output fields ---
    if isfield(bl, 'Env_VelU') && isstruct(Reggrid_Env_out) && ...
       isfield(Reggrid_Env_out, 'VelU')
        fprintf('  Gridded Env output:\n');
        [p, f] = compare_cell_field(bl.Env_VelU, Reggrid_Env_out, 'VelU', 'Env_VelU', vel_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_cell_field(bl.Env_VelV, Reggrid_Env_out, 'VelV', 'Env_VelV', vel_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_cell_field(bl.Env_Press, Reggrid_Env_out, 'Press', 'Env_Press', press_tol);
        npass = npass + p; nfail = nfail + f;
    end

    % --- GAHM parameter fields ---
    nt_gahm = length(GAHM_out);
    if nt_gahm ~= bl.nt_gahm
        fprintf('  FAIL: GAHM timestep count mismatch (baseline=%d, current=%d)\n', bl.nt_gahm, nt_gahm);
        nfail = nfail + 1;
    else
        fprintf('  GAHM parameters (%d track times):\n', nt_gahm);

        [p, f] = compare_vector(bl.GAHM_B, [GAHM_out.B], 'GAHM.B', param_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_vector(bl.GAHM_Rmax_in, [GAHM_out.Rmax_in], 'GAHM.Rmax_in', dist_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_vector(bl.GAHM_Rmax_tot, [GAHM_out.Rmax_tot], 'GAHM.Rmax_tot', dist_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_vector(bl.GAHM_SVorMax, [GAHM_out.SVorMax_10_10], 'GAHM.SVorMax', vel_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_cell_array(bl.GAHM_Rmax, {GAHM_out.Rmax}, 'GAHM.Rmax', dist_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_cell_array(bl.GAHM_Bg, {GAHM_out.Bg}, 'GAHM.Bg', param_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_cell_array(bl.GAHM_phi, {GAHM_out.phi}, 'GAHM.phi', param_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_cell_array(bl.GAHM_RmaxQ, {GAHM_out.RmaxQ}, 'GAHM.RmaxQ', dist_tol);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_cell_array(bl.GAHM_flag, {GAHM_out.flag}, 'GAHM.flag', 0);
        npass = npass + p; nfail = nfail + f;
    end

    % --- Track data ---
    nt_track = length(Trackdata);
    if nt_track ~= bl.nt_track
        fprintf('  FAIL: Track timestep count mismatch (baseline=%d, current=%d)\n', bl.nt_track, nt_track);
        nfail = nfail + 1;
    else
        fprintf('  Track data (%d output times):\n', nt_track);
        [p, f] = compare_vector(bl.Track_Lat, [Trackdata.Lat], 'Track.Lat', 1e-12);
        npass = npass + p; nfail = nfail + f;

        [p, f] = compare_vector(bl.Track_Lon, [Trackdata.Lon], 'Track.Lon', 1e-12);
        npass = npass + p; nfail = nfail + f;
    end
end


function [npass, nfail] = compare_cell_field(bl_cells, struct_array, fieldname, label, tol)
    npass = 0;
    nfail = 0;
    max_abs_diff = 0;
    max_rel_diff = 0;
    for i = 1:length(bl_cells)
        bl_data  = bl_cells{i};
        cur_data = struct_array(i).(fieldname);
        if ~isequal(size(bl_data), size(cur_data))
            fprintf('    FAIL: %s size mismatch at t=%d\n', label, i);
            nfail = nfail + 1;
            return
        end
        both_nan = isnan(bl_data) & isnan(cur_data);
        bl_only_nan = isnan(bl_data) & ~isnan(cur_data);
        cur_only_nan = ~isnan(bl_data) & isnan(cur_data);
        if any(bl_only_nan(:)) || any(cur_only_nan(:))
            fprintf('    FAIL: %s NaN pattern mismatch at t=%d\n', label, i);
            nfail = nfail + 1;
            return
        end
        valid = ~both_nan;
        if any(valid(:))
            adiff = abs(bl_data(valid) - cur_data(valid));
            max_abs_diff = max(max_abs_diff, max(adiff(:)));
            denom = max(abs(bl_data(valid)), 1e-15);
            rdiff = adiff ./ denom;
            max_rel_diff = max(max_rel_diff, max(rdiff(:)));
        end
    end
    if max_abs_diff <= tol
        fprintf('    PASS: %-20s max_abs=%.2e  max_rel=%.2e\n', label, max_abs_diff, max_rel_diff);
        npass = 1;
    else
        fprintf('    FAIL: %-20s max_abs=%.2e  max_rel=%.2e  (tol=%.2e)\n', label, max_abs_diff, max_rel_diff, tol);
        nfail = 1;
    end
end


function [npass, nfail] = compare_vector(bl_vec, cur_vec, label, tol)
    npass = 0;
    nfail = 0;
    if length(bl_vec) ~= length(cur_vec)
        fprintf('    FAIL: %s length mismatch (baseline=%d, current=%d)\n', label, length(bl_vec), length(cur_vec));
        nfail = 1;
        return
    end
    both_nan = isnan(bl_vec) & isnan(cur_vec);
    bl_only_nan = isnan(bl_vec) & ~isnan(cur_vec);
    cur_only_nan = ~isnan(bl_vec) & isnan(cur_vec);
    if any(bl_only_nan) || any(cur_only_nan)
        fprintf('    FAIL: %s NaN pattern mismatch\n', label);
        nfail = 1;
        return
    end
    valid = ~both_nan;
    if any(valid)
        adiff = abs(bl_vec(valid) - cur_vec(valid));
        max_abs = max(adiff);
        denom = max(abs(bl_vec(valid)), 1e-15);
        max_rel = max(adiff ./ denom);
    else
        max_abs = 0;
        max_rel = 0;
    end
    if max_abs <= tol
        fprintf('    PASS: %-20s max_abs=%.2e  max_rel=%.2e\n', label, max_abs, max_rel);
        npass = 1;
    else
        fprintf('    FAIL: %-20s max_abs=%.2e  max_rel=%.2e  (tol=%.2e)\n', label, max_abs, max_rel, tol);
        nfail = 1;
    end
end


function [npass, nfail] = compare_cell_array(bl_cells, cur_cells, label, tol)
    npass = 0;
    nfail = 0;
    max_abs_diff = 0;
    max_rel_diff = 0;
    if length(bl_cells) ~= length(cur_cells)
        fprintf('    FAIL: %s count mismatch\n', label);
        nfail = 1;
        return
    end
    for i = 1:length(bl_cells)
        bl_data  = bl_cells{i};
        cur_data = cur_cells{i};
        if ~isequal(size(bl_data), size(cur_data))
            fprintf('    FAIL: %s size mismatch at t=%d\n', label, i);
            nfail = 1;
            return
        end
        both_nan = isnan(bl_data) & isnan(cur_data);
        bl_only_nan = isnan(bl_data) & ~isnan(cur_data);
        cur_only_nan = ~isnan(bl_data) & isnan(cur_data);
        if any(bl_only_nan(:)) || any(cur_only_nan(:))
            fprintf('    FAIL: %s NaN pattern mismatch at t=%d\n', label, i);
            nfail = 1;
            return
        end
        valid = ~both_nan;
        if any(valid(:))
            adiff = abs(bl_data(valid) - cur_data(valid));
            max_abs_diff = max(max_abs_diff, max(adiff(:)));
            denom = max(abs(bl_data(valid)), 1e-15);
            rdiff = adiff ./ denom;
            max_rel_diff = max(max_rel_diff, max(rdiff(:)));
        end
    end
    if max_abs_diff <= tol
        fprintf('    PASS: %-20s max_abs=%.2e  max_rel=%.2e\n', label, max_abs_diff, max_rel_diff);
        npass = 1;
    else
        fprintf('    FAIL: %-20s max_abs=%.2e  max_rel=%.2e  (tol=%.2e)\n', label, max_abs_diff, max_rel_diff, tol);
        nfail = 1;
    end
end
