function storm = createOutputStruct(OUTPUT, time, real_lon, real_lat, era5_lon, era5_lat)

    % Normalize all longitudes to -180..180 for downstream consumers
    output_lon = OUTPUT.lon;
    output_lon(output_lon > 180) = output_lon(output_lon > 180) - 360;
    real_lon(real_lon > 180) = real_lon(real_lon > 180) - 360;
    era5_lon(era5_lon > 180) = era5_lon(era5_lon > 180) - 360;
    mask = 1 - OUTPUT.mask;
    mask_inner = 1 - OUTPUT.mask_inner;
    
    storm = struct( ...
        'Time', time, ...
        'Lo', output_lon, ...
        'La', OUTPUT.lat, ...
        'Vortex_mask', mask, ...
        'Vortex_mask_inner', mask_inner, ...
        'env_msl', OUTPUT.slp, ...
        'env_u10', OUTPUT.u, ...
        'env_v10', OUTPUT.v, ...
        'hur_msl', OUTPUT.dis_slp, ...
        'hur_u10', OUTPUT.dis_u, ...
        'hur_v10', OUTPUT.dis_v, ...
        'BestTrack_lon', real_lon, ...
        'BestTrack_lat', real_lat, ...
        'distance_outer', OUTPUT.distance_outer, ...
        'distance_inner', OUTPUT.distance_inner, ...
        'min_pressure_center_lon', era5_lon, ...
        'min_pressure_center_lat', era5_lat ...
    );
    
    varnames = ["env_msl", "env_u10", "env_v10", "hur_msl", "hur_u10", "hur_v10"];
    varunits = ["mb", "m/s", "m/s", "mb", "m/s", "m/s"];
    storm.units = dictionary(varnames, varunits);
end
